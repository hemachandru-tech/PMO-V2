"""Wording-noise gold set (ENH-022, US-220; FEAT-072 / FEAT-064).

People ask with filler, grammar and tense the gold questions don't have: "How many number of project will be active
in UAE region" (EXEC-139) answered 0 at confidence 1.0 because "will" became a filter. This module wraps each
approved original with that kind of noise, deterministically (no LLM), so the same wording is tested every run:

* ``polite`` — "Kindly tell me …"; ``filler`` — "I would like to know …";
* ``number_of`` — "How many number of …"; ``future`` — "… will be …" (or "… going forward");
* ``singular`` — "projects" → "project"; ``typo`` — two neighbouring letters of the longest word swapped.

Each variant must plan the same spec as its original. The pack's `noise` examples are this module's output
(``noise_examples``), written after the marker in ``gold_examples.yaml`` by ``python -m tela_api.knowledge.noise``;
``tests/test_noise_set_unit.py`` checks the file still matches and scores the set.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path
from typing import Any

import yaml

KINDS = ("polite", "filler", "number_of", "future", "singular", "typo")
MARKER = "  # --- noise (US-220): generated by `uv run python -m tela_api.knowledge.noise`; do not edit by hand ---"
# The EXEC-139 question itself, with the answer the data supports (35 open projects in GCC - UAE on Dataverse).
EXEC139 = {"question": "How many number of project will be active in UAE region", "tags": ["noise", "exec139"],
           "held_out": True, "shape": "number",
           "spec": {"measure": {"ref": "measure:open_projects"},
                    "filters": [{"ref": "dimension:region", "op": "=", "values": ["GCC - UAE"]}]}}


def _body(question: str) -> str:
    q = " ".join(question.split()).rstrip("?").strip()
    return q[:1].lower() + q[1:] if q[:2] != q[:2].upper() else q  # keep "KSA …", lower "How …"


def _typo(q: str) -> str | None:
    longest = max(re.findall(r"[A-Za-z]{7,}", q), key=len, default=None)
    if longest is None:
        return None
    i = len(longest) // 2
    swapped = longest[:i - 1] + longest[i] + longest[i - 1] + longest[i + 1:]
    return None if swapped == longest else q.replace(longest, swapped, 1)


def variants(question: str) -> list[tuple[str, str]]:
    """The noisy forms of one question, in ``KINDS`` order; a kind that doesn't apply is left out."""
    q = " ".join(question.split()).rstrip("?").strip()
    out: list[tuple[str, str]] = [("polite", f"Kindly tell me {_body(q)}"),
                                  ("filler", f"I would like to know {_body(q)}")]
    if re.match(r"(?i)how many\b", q):
        out.append(("number_of", re.sub(r"(?i)^how many\b", "How many number of", q)))
    if re.search(r"\b(are|is)\b", q):
        out.append(("future", re.sub(r"\b(are|is)\b", "will be", q, count=1)))
    else:
        out.append(("future", f"{q} going forward"))
    if re.search(r"\b(projects|requests)\b", q):
        out.append(("singular", re.sub(r"\b(project|request)s\b", r"\1", q, count=1)))
    if (t := _typo(q)) is not None:
        out.append(("typo", t))
    return [(k, v) for k, v in out if v.lower() != q.lower()]


def originals(examples: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """The examples noise is built from: single-turn, not held out, no filter values (they differ by source)."""
    return [e for e in examples if not e.get("held_out") and not e.get("turns") and not e["spec"].get("filters")]


def noise_examples(examples: list[dict[str, Any]]) -> list[dict[str, Any]]:
    out = [dict(EXEC139)]
    for e in originals(examples):
        for kind, q in variants(e["question"]):
            out.append({"question": q, "tags": ["noise", kind], "held_out": True, "noise_of": e["question"],
                        **({"shape": e["shape"]} if e.get("shape") else {}), "spec": e["spec"]})
    return out


def write(path: Path) -> int:
    """Rewrite the generated block of ``gold_examples.yaml`` (everything after ``MARKER``)."""
    text = path.read_text()
    head = text.split(MARKER, 1)[0].rstrip("\n")
    examples = [e for e in (yaml.safe_load(head) or {}).get("examples") or [] if "noise" not in (e.get("tags") or [])]
    made = noise_examples(examples)
    path.write_text("\n".join([head, MARKER, *(_entry(e) for e in made)]) + "\n")
    return len(made)


def _flow(value: Any) -> str:
    """One value on one line, in the file's own flow style ({measure: {ref: "measure:open_projects"}})."""
    out = yaml.dump(value, Dumper=_NoAliases, default_flow_style=True, sort_keys=False, width=10_000,
                    allow_unicode=True)
    return str(out).strip().removesuffix("...").strip()


class _NoAliases(yaml.SafeDumper):  # type: ignore[misc]
    def ignore_aliases(self, data: Any) -> bool:
        return True


def _entry(e: dict[str, Any]) -> str:
    lines = [f"  - question: {_flow(e['question'])}", f"    tags: {_flow(e['tags'])}", "    held_out: true"]
    if "noise_of" in e:
        lines.append(f"    noise_of: {_flow(e['noise_of'])}")
    if e.get("shape"):  # US-250
        lines.append(f"    shape: {e['shape']}")
    lines.append(f"    spec: {_flow(e['spec'])}")
    return "\n".join(lines)


if __name__ == "__main__":  # pragma: no cover - a maintainer's tool
    from tela_api.packs.manifest import DEFAULT_PACKS_DIR

    target = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_PACKS_DIR / "pmo" / "gold_examples.yaml"
    print(f"{write(target)} noise examples written to {target}")
