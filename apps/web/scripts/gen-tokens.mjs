// Generates src/design/tokens.css from src/design/tokens.json (US-134).
//
// tokens.json is exported from the Claude Design system (US-132) and is the one source for colours, type, spacing,
// radii, shadows and sizes. This script writes:
//   * CSS variables (--tl-*) for the light theme on :root and [data-theme="light"], and for the dark theme on
//     [data-theme="dark"] (and on :root without data-theme when the OS prefers dark, before the app sets it);
//   * a Tailwind v4 @theme block that maps utilities (bg-surface-raised, text-ink, rounded-md, text-heading …) to those
//     variables, replacing Tailwind's default palette, type scale, radii and shadows so only tokens can be used.
//
// Run with `pnpm tokens`; `pnpm tokens --check` fails when tokens.css is out of date (run by the unit tests too).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(root, "src/design/tokens.json");
const TARGET = join(root, "src/design/tokens.css");

/** shadcn/ui names mapped to Tela tokens, so components copied from shadcn keep working. Tela's `accent` is the
 * primary action colour; shadcn's `accent` (a hover fill) is spelled `accent-soft` in our components. */
const SHADCN_ALIASES = {
  background: "surface",
  foreground: "ink",
  card: "surface-raised",
  "card-foreground": "ink",
  popover: "surface-raised",
  "popover-foreground": "ink",
  primary: "accent",
  "primary-foreground": "on-accent",
  secondary: "surface-sunken",
  "secondary-foreground": "ink",
  muted: "surface-sunken",
  "muted-foreground": "ink-muted",
  destructive: "status-danger",
  "destructive-foreground": "on-danger",
  border: "line",
  input: "line-strong",
  ring: "focus",
};

function themed(value, theme) {
  return typeof value === "string" ? value : value[theme];
}

/** Resolves "{accent}" style aliases to a CSS variable reference. */
function cssValue(value) {
  const alias = /^\{([a-z0-9-]+)\}$/.exec(value);
  return alias ? `var(--tl-${alias[1]})` : value;
}

export function generate(tokens) {
  const colors = tokens.color.tokens;
  const shadows = tokens.shadow.tokens;
  const themedVars = (theme) => [
    ...colors.map((t) => `  --tl-${t.name}: ${cssValue(themed(t.value, theme))};`),
    ...shadows.map((t) => `  --tl-${t.name}: ${themed(t.value, theme)};`),
  ];
  const fixed = [
    ...Object.entries(tokens.type.families).map(([k, v]) => `  --tl-font-${k}: ${v};`),
    ...tokens.spacing.tokens.map((t) => `  --tl-${t.name}: ${t.value};`),
    ...tokens.radius.tokens.map((t) => `  --tl-${t.name}: ${t.value};`),
    ...tokens.size.tokens.map((t) => `  --tl-${t.name}: ${t.value};`),
  ];
  const typeStyles = tokens.type.groups.flatMap((g) => g.styles.map((s) => ({ ...s, family: g.family })));
  const themeBlock = [
    "  --color-*: initial;",
    "  --color-transparent: transparent;",
    "  --color-current: currentColor;",
    ...colors.map((t) => `  --color-${t.name}: var(--tl-${t.name});`),
    ...Object.entries(SHADCN_ALIASES).map(([alias, name]) => `  --color-${alias}: var(--tl-${name});`),
    "",
    "  --font-*: initial;",
    ...Object.keys(tokens.type.families).map((k) => `  --font-${k}: var(--tl-font-${k});`),
    "",
    "  --text-*: initial;",
    ...typeStyles.flatMap((s) => [
      `  --text-${s.name}: ${s.fontSize};`,
      `  --text-${s.name}--line-height: ${s.lineHeight};`,
      `  --text-${s.name}--font-weight: ${s.fontWeight};`,
      ...(s.letterSpacing ? [`  --text-${s.name}--letter-spacing: ${s.letterSpacing};`] : []),
    ]),
    "",
    "  /* space-N = N × 4px, so p-2 is space-2 (8px) and gap-6 is space-6 (24px). */",
    "  --spacing: 4px;",
    ...tokens.size.tokens.map((t) => `  --spacing-${t.name}: var(--tl-${t.name});`),
    "",
    "  --radius-*: initial;",
    ...tokens.radius.tokens.map((t) => `  --${t.name}: var(--tl-${t.name});`),
    "",
    "  --shadow-*: initial;",
    ...shadows.map((t) => `  --shadow-${t.name.replace(/^shadow-/, "")}: var(--tl-${t.name});`),
  ];
  return [
    "/* GENERATED by scripts/gen-tokens.mjs from tokens.json (Claude Design, US-132). Do not edit; run `pnpm tokens`. */",
    "",
    ':root,\n[data-theme="light"] {',
    "  color-scheme: light;",
    ...themedVars("light"),
    "}",
    "",
    '[data-theme="dark"] {',
    "  color-scheme: dark;",
    ...themedVars("dark"),
    "}",
    "",
    "@media (prefers-color-scheme: dark) {",
    "  :root:not([data-theme]) {",
    "    color-scheme: dark;",
    ...themedVars("dark").map((l) => `  ${l}`),
    "  }",
    "}",
    "",
    ":root {",
    ...fixed,
    "}",
    "",
    "@theme inline {",
    ...themeBlock,
    "}",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = generate(JSON.parse(readFileSync(SOURCE, "utf8")));
  if (process.argv.includes("--check")) {
    if (readFileSync(TARGET, "utf8") !== css) {
      console.error("src/design/tokens.css is out of date with tokens.json; run `pnpm tokens`.");
      process.exit(1);
    }
  } else {
    writeFileSync(TARGET, css);
    console.log(`wrote ${TARGET}`);
  }
}
